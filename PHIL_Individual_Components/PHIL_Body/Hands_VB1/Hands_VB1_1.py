def _sort_by_angle(pts):
    cx = sum(p[0] for p in pts) / len(pts)
    cy = sum(p[1] for p in pts) / len(pts)
    return sorted(pts, key=lambda p: _math.atan2(p[1] - cy, p[0] - cx))

