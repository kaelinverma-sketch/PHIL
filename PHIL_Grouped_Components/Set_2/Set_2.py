def make_helix_wire(cx, cy, base_z, r_helix, pitch, height, start_angle=0.0):
    turns  = height / pitch
    n_pts  = max(120, int(turns * 120))
    pts    = TColgp_Array1OfPnt(1, n_pts + 1)
    for i in range(n_pts + 1):
        t     = i / n_pts
        angle = start_angle + t * turns * 2 * math.pi
        pts.SetValue(i + 1, gp_Pnt(
            cx + r_helix * math.cos(angle),
            cy + r_helix * math.sin(angle),
            base_z + t * height))
    bspline = GeomAPI_PointsToBSpline(pts, 3, 8, GeomAbs_C2, 1e-3).Curve()
    edge    = BRepBuilderAPI_MakeEdge(bspline).Edge()
    return BRepBuilderAPI_MakeWire(edge).Wire()


def make_triangle_wire(cx, cy, base_z, angle0, r_helix):
    side  = 31.0
    h_tri = side * math.sqrt(3) / 2.0
    rad_x =  math.cos(angle0)
    rad_y =  math.sin(angle0)
    bm_x  = cx + r_helix * rad_x
    bm_y  = cy + r_helix * rad_y
    half  = side / 2.0
    B1 = gp_Pnt(bm_x,                 bm_y,                 base_z + half)
    B2 = gp_Pnt(bm_x,                 bm_y,                 base_z - half)
    A  = gp_Pnt(bm_x - h_tri * rad_x, bm_y - h_tri * rad_y, base_z)
    e1 = BRepBuilderAPI_MakeEdge(B1, B2).Edge()
    e2 = BRepBuilderAPI_MakeEdge(B2, A).Edge()
    e3 = BRepBuilderAPI_MakeEdge(A,  B1).Edge()
    return BRepBuilderAPI_MakeWire(e1, e2, e3).Wire()


def make_thread_solid(cx, cy, base_z, pitch, height, r_helix, start_angle=0.0):
    helix   = make_helix_wire(cx, cy, base_z, r_helix, pitch, height, start_angle)
    profile = make_triangle_wire(cx, cy, base_z, start_angle, r_helix)
    pipe    = BRepOffsetAPI_MakePipeShell(helix)
    pipe.SetMode(True)
    pipe.Add(profile)
    pipe.Build()
    pipe.MakeSolid()
    return pipe.Shape()


