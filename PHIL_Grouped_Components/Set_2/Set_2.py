def dedupe_points(pts, tol=0.5):
    """Remove consecutive near-duplicate points within tolerance."""
    clean = [pts[0]]
    for p in pts[1:]:
        if abs(p[0] - clean[-1][0]) > tol or abs(p[1] - clean[-1][1]) > tol:
            clean.append(p)
    return clean

