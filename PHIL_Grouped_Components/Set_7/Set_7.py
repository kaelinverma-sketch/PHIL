SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))

def load_face(filename, axis_a, axis_b):
    path = os.path.join(SCRIPT_DIR, filename)
    with open(path) as f:
        data = json.load(f)
    key = list(data.keys())[0]
    wire_defs = data[key][0]
    outer = [w for w in wire_defs if w["is_outer"]]
    inner = [w for w in wire_defs if not w["is_outer"]]

    def make_wire(seg_list):
        edges = []
        for seg in seg_list:
            s = seg["start"]
            e = seg["end"]
            edges.append(Edge.make_line(
                Vector(s[axis_a], s[axis_b], 0),
                Vector(e[axis_a], e[axis_b], 0),
            ))
        return Wire(edges)

    outer_wire = make_wire(outer[0]["segments"])
    hole_wires = [make_wire(w["segments"]) for w in inner]
    return Face(outer_wire).make_holes(hole_wires) if hole_wires else Face(outer_wire)


