def sort_by_angle(pts):
    cx = sum(p[0] for p in pts)/len(pts)
    cz = sum(p[2] for p in pts)/len(pts)
    return sorted(pts, key=lambda p: math.atan2(p[2]-cz, p[0]-cx))

def make_wire_xz(pts, y_val):
    sp = sort_by_angle(pts)
    edges = []
    for i in range(len(sp)):
        s = sp[i]; e = sp[(i+1)%len(sp)]
        edges.append(Edge.make_line(Vector(s[0], y_val, s[2]), Vector(e[0], y_val, e[2])))
    return Wire(edges)

